def test_feedback_draft_never_overwrites_hand_edits(tmp_path):
    first = write_feedback(tmp_path, "# Draft\n\nv1\n")
    assert first.name == "FEEDBACK_DRAFT.md"
    assert write_feedback(tmp_path, "# Draft\n\nv2\n").name == "FEEDBACK_DRAFT.md"  # unedited: regenerated in place
    first.write_text(first.read_text() + "\nMy own note.\n")
    second = write_feedback(tmp_path, "# Draft\n\nv3\n")
    assert second.name == "FEEDBACK_DRAFT.new.md" and "My own note." in first.read_text()


def test_end_to_end_report_from_a_buggy_server(settings):
    settings.defaults["n_screen"] = 4
    fake = FakeTokenFactory(honor_chat_template_kwargs=False, coerce_digit_strings=True)
    console = Console(record=True, width=200)
    code = asyncio.run(run_stage(settings, console, stage="screen", contracts_spec="T2,T3.leading_zero,T5.flat_basic",
                                 prereg=False, yes=True, transport=fake.transport(), retry_5xx_delay_s=0))
    assert code == 0
    out = settings.root / "docs"
    paths = build_report(settings, default_runs(settings.runs_dir), out)
    html = paths["html"].read_text()
    for anchor in ('id="trust"', 'id="findings"', 'id="comparisons"', 'id="docs"', 'id="methods"', 'id="data"'):
        assert anchor in html
    assert "Tool argument changes JSON type" in html and "Thinking switch does not turn reasoning off" in html
    assert "Unreliable" in html and "prefers-color-scheme: dark" in html
    assert not re.search(r"<(link|script)[^>]+(src|href)=\"https?://", html), "report must not load external resources"
    assert "test-key-not-real" not in html
    data_files = sorted(p.name for p in (out / "data").iterdir())
    assert any(n.endswith(".calls.jsonl.gz") for n in data_files) and "cells.json" in data_files
    findings_md = paths["findings"].read_text()
    assert "## What to trust" in findings_md and "TYPE_COERCED" not in findings_md.split("## Findings")[0]
    feedback = paths["feedback"].read_text()
    assert feedback.startswith("<!-- generated by `second-opinion report`; sha256=")
    assert "## Top 5 issues" in feedback and "1. **Tool argument changes JSON type" in feedback
    assert "## Nemotron 3 Super (`nvidia/nemotron-3-super-120b-a12b`)" in feedback
