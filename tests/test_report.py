def cell(contract, model, cond, n, fails):
    s = analysis.CellStats(f"{contract}{model}{cond}", contract, model, cond.as_dict())
    s.n, s.fails = n, fails
    return s


def test_trust_matrix_colors():
    cells = {c.cell_id: c for c in [
        cell("T3.markup", SUPER, Condition(True, False, variant="markup"), 50, 20),            # red: Wilson lo >> 1%
        cell("T3.markup", SUPER, Condition(True, True, variant="markup"), 50, 0),
        cell("T5.flat_basic", SUPER, Condition(False, variant="flat_basic"), 300, 1),          # amber: lo < 1%
        cell("T5.flat_basic", SUPER, Condition(True, variant="flat_basic"), 300, 0),           # green
        cell("T2.default", SUPER, Condition(None), 50, 0),                                      # informational: ignored
    ]}
    row = trust_matrix(cells, [SUPER])[SUPER]
    assert row["tool_args"].status == "red" and row["tool_args"].worst["contract_id"] == "T3.markup"
    assert row["tool_args_stream"].status == "green"
    assert row["structured_output"].status == "amber"
    assert row["structured_output_reasoning"].status == "green" and abs(row["structured_output_reasoning"].bound - 0.01) < 1e-9
    assert row["reasoning_control"].status == "none" and row["reasoning_leak"].status == "none"


def test_family_results_detect_a_real_difference():
    v = "leading_zero"
    cells = {c.cell_id: c for c in [
        cell("T3.leading_zero", SUPER, Condition(True, True, variant=v), 300, 60),
        cell("T3.leading_zero", SUPER, Condition(True, False, variant=v), 300, 2),
        cell("T3.leading_zero", SUPER, Condition(False, False, variant=v), 300, 3),
    ]}
    fams = family_results(cells, [SUPER], 0.01)
    [f1] = fams["F1"]
    assert f1["significant"] and f1["a"]["label"] == "stream"
    [f2] = fams["F2"]
    assert not f2["significant"]
    assert fams["F3"] == []


