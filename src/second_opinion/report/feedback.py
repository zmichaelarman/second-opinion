"""docs/findings.md and FEEDBACK_DRAFT.md (CLAUDE.md §12).

FEEDBACK_DRAFT.md is generated, then hand-edited. Regenerating never overwrites hand edits:
the generated file carries a hash of its own body, and if the file on disk no longer matches
that hash, the new draft goes to FEEDBACK_DRAFT.new.md instead.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any

from .build import OWNER_LABEL, SEVERITY_LABEL, ReportData, model_short

MARK = re.compile(r"^<!-- generated by `second-opinion report`; sha256=([0-9a-f]{64}) -->\n", re.M)
ROLE_USE = {
    "ultra": "test subject, and the Investigator's hypothesis model (proposes root causes)",
    "super": "test subject, and the code writer (Investigator experiments and docs repairs)",
}


def _sev(f: dict[str, Any]) -> str:
    code, label, _ = SEVERITY_LABEL[f["severity"]]
    return f"{code} {label}"


def ranked_issues(d: ReportData) -> list[dict[str, Any]]:
    """Platform/model findings and docs findings in one priority order: severity, then reach."""
    issues = []
    for f in d.findings:
        reach = len(f.get("models") or []) * max((a["rate"] for a in f.get("arms") or []), default=0)
        issues.append({"kind": "finding", "severity": f["severity"], "reach": reach, "f": f})
    for f in (d.docs or {}).get("findings", []):
        issues.append({"kind": "docs", "severity": f["severity"], "reach": 0.0, "f": f})
    order = {"S1_SILENT": 1, "S2_LOUD": 2, "S3_GAP": 3, "S4_DOCS": 4}
    return sorted(issues, key=lambda i: (order[i["severity"]], -i["reach"]))


def _issue_line(i: dict[str, Any]) -> str:
    f = i["f"]
    if i["kind"] == "docs":
        return (f"**Docs example broken: {f['page_title']} (line {f['line']})** ({_sev(f)}). "
                f"{', '.join(f['codes'])}. {('Verified fix attached.' if f.get('fixed') else '')} <{f['page_url']}>")
    extra = f" Cause: {f['factor']}." if f.get("factor") else ""
    work = f" Workaround: {f['workaround']}." if f.get("workaround") else ""
    return (f"**{f['title']}** ({_sev(f)}; owner: {OWNER_LABEL.get(f['owner'], f['owner'])}). "
            f"{f['summary']}{extra}{work} See docs/findings.md#{f['id']}.")


def parse_friction(root: Path) -> list[dict[str, str]]:
    path = root / "FRICTION_LOG.md"
    if not path.exists():
        return []
    rows = []
    for line in path.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 6 and re.match(r"\d{4}-\d{2}-\d{2}", cells[0]):
            rows.append(dict(zip(["time", "step", "expected", "happened", "minutes", "severity"], cells)))
    return rows


def _green_cells(d: ReportData, model: str | None = None) -> list[str]:
    out = []
    for m in d.models if model is None else [model]:
        for key, label in d.columns.items():
            c = d.matrix[m][key]
            if c.status == "green":
                out.append(f"{label} on {d.names.get(m, model_short(m))}: 0 failures in {c.n} trials (failure rate < {c.bound:.1%})")
    return out


def render_findings_md(d: ReportData) -> str:
    lines = ["# Second Opinion findings", "", f"Generated {d.generated}. Data: {', '.join(d.runs) or 'none'}.", ""]
    lines += ["## What to trust", "", "| Model | " + " | ".join(d.columns.values()) + " |", "|---" * (len(d.columns) + 1) + "|"]
    for m in d.models:
        lines.append(f"| {d.names.get(m, model_short(m))} | " + " | ".join(f"{d.matrix[m][k].label}: {d.matrix[m][k].text}" for k in d.columns) + " |")
    lines += ["", "## Findings", ""]
    if d.findings_status == "clusters":
        lines += ["Failure clusters before investigation; owners are unknown until the reference replay.", ""]
    for f in d.findings:
        lines += [f'<a id="{f["id"]}"></a>', f"### {f['title']}", "",
                  f"- Severity: {_sev(f)}", f"- Owner: {OWNER_LABEL.get(f['owner'], f['owner'])}",
                  f"- Models: {', '.join(model_short(m) for m in f.get('models') or [])}", f"- {f['summary']}"]
        if f.get("factor"):
            lines.append(f"- Cause: {f['factor']}" + (f" (adjusted p = {f['p_value']:.2g})" if f.get("p_value") is not None else ""))
        if f.get("workaround"):
            lines.append(f"- Workaround: {f['workaround']}")
        if f.get("arms"):
            lines += ["", "| Arm | Failed | Trials | Rate | 95% CI |", "|---|---:|---:|---:|---:|"]
            lines += [f"| {a['label']} | {a['k']} | {a['n']} | {a['rate']:.1%} | {a['lo']:.1%}-{a['hi']:.1%} |" for a in f["arms"]]
        if f.get("repro"):
            lines += ["", "Minimal repro:", "", "```bash", f["repro"]["curl"], "```"]
        lines.append("")
    if d.docs:
        s = d.docs["summary"]
        lines += ["## Docs health", "", f"{s['examples_passing']} of {s['examples_checked']} checked code examples pass; "
                  f"{s['findings']} findings; {s['repaired']} repaired.", ""]
        for f in d.docs["findings"]:
            lines.append(f"- [{f['page_title']}]({f['page_url']}) line {f['line']}: {', '.join(f['codes'])} "
                         f"({SEVERITY_LABEL[f['severity']][0]}){' - repaired' if f.get('fixed') else ''}")
        lines.append("")
    lines += ["## Pre-registered comparisons", ""]
    for fam, rows in d.families.items():
        sig = [r for r in rows if r["significant"]]
        lines.append(f"- {fam} ({d.family_specs[fam]['name']}): {len(sig)} of {len(rows)} comparisons significant"
                     + ("".join(f"; {model_short(r['model'])} {r['contract_id']}: {r['a']['label']} {r['a']['rate']:.1%} vs "
                                f"{r['b']['label']} {r['b']['rate']:.1%} (p_holm {r['p_holm']:.2g})" for r in sig)))
    return "\n".join(lines) + "\n"


def render_feedback(d: ReportData, root: Path) -> str:
    issues = ranked_issues(d)
    friction = parse_friction(root)
    t = d.totals
    lines = [
        "# Feedback: Nebius Token Factory and NVIDIA Nemotron",
        "",
        "Drafted by `second-opinion report` from the measured data. Edit freely: regenerating never overwrites your edits. "
        "Lines marked [edit] need a human answer.",
        "",
        "## Top 5 issues",
        "",
    ]
    lines += [f"{n}. {_issue_line(i)}" for n, i in enumerate(issues[:5], 1)] or ["1. [edit] No issues found in these runs."]
    lines += [
        "",
        "## Nebius Token Factory",
        "",
        "### What we used it for",
        "",
        f"Every measured call went through the Token Factory chat completions API: {t['trials']:,} analyzed trials over "
        f"{t['cells']} test cells on {t['models']} Nemotron models (${t['cost_usd']:.2f} in total). Second Opinion also runs "
        "its own agents on Token Factory: Nemotron 3 Ultra proposes root causes and Nemotron 3 Super writes experiment code "
        "and docs fixes.",
        "",
        "### What worked",
        "",
    ]
    greens = _green_cells(d)
    lines += [f"- {g}" for g in greens] or ["- [edit]"]
    if d.docs:
        s = d.docs["summary"]
        lines.append(f"- {s['examples_passing']} of {s['examples_checked']} checked docs code examples pass as written.")
    lines += ["", "### What needs work", ""]
    platform = [i for i in issues if i["kind"] == "docs" or i["f"].get("owner") in ("nebius_platform", "nebius_docs", "unknown")]
    lines += [f"- {_issue_line(i)}" for i in platform] or ["- [edit]"]
    lines += ["", "### Onboarding: zero to hello world", ""]
    if friction:
        total = sum(int(r["minutes"]) for r in friction if r["minutes"].isdigit())
        lines.append(f"From FRICTION_LOG.md ({len(friction)} entries, about {total} minutes lost):")
        lines.append("")
        lines += [f"- {r['time']} ET, {r['step']}: {r['happened']} ({r['minutes']} min, {r['severity']})" for r in friction]
    else:
        lines.append("- [edit] No friction logged.")
    lines += ["", "### Would we build with it again?", "", "[edit]", "",
              "## Nebius AI Cloud", "", "[edit] Not used in this project beyond Token Factory.", ""]
    for m in d.models:
        price = d.methods["prices"].get(m)
        role = getattr(price, "role", None) if price else None
        mine = [i for i in issues if i["kind"] == "finding" and m in (i["f"].get("models") or [])]
        lines += [f"## {d.names.get(m, model_short(m))} (`{m}`)", "", "### What we used it for", "",
                  ROLE_USE.get(role, "test subject") + ".", "", "### What worked", ""]
        lines += [f"- {g}" for g in _green_cells(d, m)] or ["- [edit]"]
        lines += ["", "### What needs work", ""]
        lines += [f"- {_issue_line(i)}" for i in mine] or ["- No failure clusters for this model."]
        lines += ["", "### Would we build with it again?", "", "[edit]", ""]
    return "\n".join(lines)


def write_feedback(root: Path, body: str) -> Path:
    digest = hashlib.sha256(body.encode()).hexdigest()
    text = f"<!-- generated by `second-opinion report`; sha256={digest} -->\n{body}"
    path = root / "FEEDBACK_DRAFT.md"
    if path.exists():
        current = path.read_text()
        m = MARK.match(current)
        unedited = m is not None and hashlib.sha256(current[m.end():].encode()).hexdigest() == m.group(1)
        if not unedited:
            path = root / "FEEDBACK_DRAFT.new.md"
    path.write_text(text)
    return path
